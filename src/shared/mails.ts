/*
  Тексты писем, которые уходят через задачу очереди 'mail.send'
*/

export function resetPasswordMail(url: string){
  return {
    subject: 'Восстановление пароля',
    text: `Чтобы задать новый пароль, перейдите по ссылке: ${url}\nСсылка действует час и работает один раз. Если вы не запрашивали восстановление, просто проигнорируйте письмо.`
  };
}

export function passwordChangedMail(){
  return {
    subject: 'Пароль изменён',
    text: 'Пароль от вашего аккаунта только что изменён. Если это были не вы, восстановите пароль через форму входа.'
  };
}

export function emailChangeRequestedMail(newEmail: string){
  return {
    subject: 'Запрошена смена email',
    text: `Для вашего аккаунта запрошена смена email на ${newEmail}. Адрес сменится, когда по ссылке из письма на новый адрес перейдут. Если это были не вы, смените пароль.`
  };
}
