/*
  «октября 2025» — для «с нами с …» / «читатель с …». Точность — месяц, поэтому считается
  на сервере: расхождение часовых поясов на границе месяца не важно, а LocalDate дал бы
  «окт. 2025 г.»
*/
export function formatMonthSince(value: Date){
  return `${MONTHS[value.getMonth()]} ${value.getFullYear()}`;
}

const MONTHS = [ 'января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря' ];
